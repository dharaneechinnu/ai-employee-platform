class EmbeddingConfig(Base, TimestampMixin):
    """One company's choice of embedding provider.

    Chosen once per company, not per AI Employee: every memory must be
    embedded by the same model for distances to mean anything.
    """

    __tablename__ = "embedding_configs"

    owner_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True
    )
    provider_key: Mapped[str] = mapped_column(String(50), nullable=False, default="local")
    model: Mapped[str] = mapped_column(String(100), nullable=False)
    dim: Mapped[int] = mapped_column(Integer, nullable=False)
    # NULL for the local provider, which needs no key.
    api_key_enc: Mapped[bytes | None] = mapped_column(LargeBinary)


class RunSummary(Base, TimestampMixin):
    """What a finished run distilled into.

    This is how an employee stops repeating a mistake: a later, similar
    task can recall what happened last time.
    """

    __tablename__ = "run_summaries"

    run_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("runs.id", ondelete="CASCADE"), primary_key=True
    )
    owner_id: Mapped[uuid.UUID] = mapped_column(PGUUID(as_uuid=True), nullable=False)
    goal: Mapped[str | None] = mapped_column(Text)
    outcome: Mapped[str | None] = mapped_column(Text)
    lesson: Mapped[str | None] = mapped_column(Text)

    __table_args__ = (Index("ix_run_summaries_owner", "owner_id"),)


class ReembedJob(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    """Progress for a provider switch.

    Changing embedding provider means re-processing every memory. With
    ten thousand rows that is a background job with a progress bar, not
    an instant toggle.
    """

    __tablename__ = "reembed_jobs"

    owner_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    from_model: Mapped[str | None] = mapped_column(String(100))
    to_model: Mapped[str] = mapped_column(String(100), nullable=False)
    total: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    done: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    status: Mapped[str] = mapped_column(String(20), nullable=False, default="running")
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
