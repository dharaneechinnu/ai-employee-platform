"""Memory: what an AI Employee remembers between tasks.

Without this an employee is amnesiac. You correct it on Monday and it
makes the same mistake on Tuesday.

The trap we are avoiding is the obvious fix — sending all past history
with every request. That is expensive, it fills the context window,
and it makes answers *worse*, because the one relevant fact ends up
buried in noise. So memory is retrieved deliberately, by the model
asking for it.

Vectors live in dimension-specific tables because a pgvector index
requires a fixed dimension. Mixing 768 and 1536 vectors in one column
means no index, or distance maths that is quietly meaningless.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from enum import StrEnum
from typing import Any

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    Computed,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    LargeBinary,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import JSONB, TSVECTOR
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.models.base import Base, StrEnumType, TimestampMixin, UUIDPrimaryKeyMixin

# The dimensions we support. One table each, because a pgvector index
# is built for one fixed width.
SUPPORTED_DIMENSIONS = (384, 768, 1024, 1536)


class MemoryKind(StrEnum):
    FACT = "fact"  # something true about this company
    CORRECTION = "correction"  # a human told the AI it was wrong
    SUMMARY = "summary"  # distilled from a finished run
    DOCUMENT = "document"  # a chunk of an uploaded file


class Memory(Base, UUIDPrimaryKeyMixin, TimestampMixin):
    __tablename__ = "memories"

    owner_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    kind: Mapped[MemoryKind] = mapped_column(
        StrEnumType(MemoryKind, 20), nullable=False, default=MemoryKind.FACT
    )

    content: Mapped[str] = mapped_column(Text, nullable=False)
    # Generated by Postgres, so it can never drift from `content`.
    content_tsv: Mapped[str] = mapped_column(
        TSVECTOR, Computed("to_tsvector('english', content)", persisted=True)
    )

    # Stored per row so a mismatch is always detectable. Searching
    # across two different models returns confident nonsense, which is
    # the worst kind of failure, so we refuse rather than allow it.
    embedding_model: Mapped[str] = mapped_column(String(100), nullable=False)
    embedding_dim: Mapped[int] = mapped_column(Integer, nullable=False)

    meta: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False, default=dict)
    created_by: Mapped[uuid.UUID | None] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("users.id", ondelete="SET NULL")
    )

    __table_args__ = (
        Index("ix_memories_owner", "owner_id"),
        Index("ix_memories_tsv", "content_tsv", postgresql_using="gin"),
    )


class MemoryVector384(Base):
    """384 dimensions: the local bge-small model, which is the default."""

    __tablename__ = "memory_vectors_384"
    memory_id: Mapped[uuid.UUID] = mapped_column(
        PGUUID(as_uuid=True), ForeignKey("memories.id", ondelete="CASCADE"), primary_key=True
    )
    owner_id: Mapped[uuid.UUID] = mapped_column(PGUUID(as_uuid=True), nullable=False)
    embedding: Mapped[Any] = mapped_column(Vector(384), nullable=False)


